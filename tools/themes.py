COMPILED = [(sec, name, set(arts), re.compile(w)) for sec, name, arts, w in THEMES]


def assign(q):
    arts = set(q['articles'])
    head = q['stem']
    body = head + ''.join(q['statements'].values()) + ''.join(q['options'].values())
    # 1) 条文で決まるもの  2) 問題文の語  3) 選択肢まで含めた語
    for sec, name, a, w in COMPILED:
        if a & arts:
            return name
    for src in (head, body):
        for sec, name, a, w in COMPILED:
            if w.search(src):
                return name
    return None


for q in DB:
    q['theme'] = assign(q) or 'その他'

# ---------- 条文名（出題者が本文で括弧書きしているものだけ） ----------
ARTPAT = re.compile(
    r'(貸金業法施行規則|貸金業法施行令|貸金業法|利息制限法|出資法|民法|会社法|商法|破産法|民事再生法'
    r'|民事執行法|民事訴訟法|民事保全法|手形法|電子記録債権法|消費者契約法|景品表示法)'
    r'(第\d+条(?:の\d+)*)(?:第\d+項)?\s*（([^（）]{2,26})）')
cand = collections.defaultdict(collections.Counter)
for q in DB:
    body = q['stem'] + ''.join(q['statements'].values()) + ''.join(q['options'].values())
    for m in ARTPAT.finditer(body):
        nm = m.group(3)
        if any(x in nm for x in ('という', '以下', '注', '本問')):
            continue
        cand[m.group(1) + m.group(2)][nm] += 1
ARTNAME = {k: c.most_common(1)[0][0] for k, c in cand.items()}
for q in DB:
    q['arts'] = [{'a': a, 'n': ARTNAME[a]} for a in q['articles'] if a in ARTNAME][:3]

# ---------- テーマ一覧 ----------
cnt = collections.Counter(q['theme'] for q in DB)
kai = collections.defaultdict(set)
for q in DB:
    kai[q['theme']].add(q['kai'])
GROUP = {name: sec for sec, name, _, _ in THEMES}
ARTSOF = {name: arts for _, name, arts, _ in THEMES}
THEMELIST = []
for sec in ['法令', '貸付実務', '資金需要者保護', '財務会計', 'その他']:
    for t in sorted([t for t in cnt if GROUP.get(t, 'その他') == sec], key=lambda t: -cnt[t]):
        # そのテーマの定義に含まれる条文のうち、名前が判明しているものを見出しに使う
        named = [{'a': a, 'n': ARTNAME[a]} for a in ARTSOF.get(t, []) if a in ARTNAME][:2]
        THEMELIST.append({'sec': sec, 'name': t, 'count': cnt[t],
                          'kaiCount': len(kai[t]), 'arts': named})

