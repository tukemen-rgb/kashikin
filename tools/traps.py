COMPILED = [(tid, name, tip, [[re.compile(p) for p in grp] for grp in grps])
            for tid, name, tip, grps in TRAPS]


def detect(q):
    """4つの選択肢（または記述）のあいだで対立が生じている型を返す。"""
    texts = list(q['options'].values())
    if q['statements']:
        texts = list(q['statements'].values()) + texts
    found = []
    for tid, name, tip, groups in COMPILED:
        hit = set()
        for gi, pats in enumerate(groups):
            for t in texts:
                if any(p.search(t) for p in pats):
                    hit.add(gi)
                    break
        if len(hit) >= 2:            # 相反する2グループが同じ問題に出ている
            found.append(tid)
    return found




for q in DB:
    q['traps'] = detect(q)

json.dump(DB, open('db.json', 'w'), ensure_ascii=False)
json.dump([{'id': t, 'name': n, 'tip': p} for t, n, p, _ in TRAPS],
          open('traps.json', 'w'), ensure_ascii=False)

cnt = collections.Counter(t for q in DB for t in q['traps'])
print('引っかけの型が付いた問題:', sum(1 for q in DB if q['traps']), '/', len(DB))
print('\n■ 型ごとの出現数')
for tid, name, tip, _ in TRAPS:
    print(f'  {cnt[tid]:4}問  {name}')
